"""RESEARCH (research/exec-perf): synthetic freight datasets of any size, in the exact shape of
data/freight/week2.json (same policy, kinds, sources, fields), so the approved freight skill matches them exactly.

Ground truth is the generator's own INTENT for each record, fixed before any text is written. It never parses the
lines, so it shares no code with the skill, its variant, or the core verifier. Money is integer cents throughout.

  python -m experiments.perf.gen 1000 > /tmp/f1000.json
"""
import json
import random
import sys

POLICY = {"actions": {"set_field": {"requires_approval": True, "fields": {"freight_accrued": {
              "type": "number", "min": 0, "max_abs_change": 500}}}},
          "invariants": [{"rule": "carrier_invoice_net", "field": "freight_accrued", "source": "carrier_export"}],
          "context": {"contract:kestrel-freight": "rev-2026-10"}}

# outcome classes, cycled so every size contains every class
CLASSES = ("ok", "ok", "ok", "ok", "wrong", "wrong", "cad", "bad_trailer", "no_invoice", "unknown_code", "duplicate")
EXPECT = {"ok": "no_change", "wrong": "change_proposed", "cad": "requires_review", "bad_trailer": "insufficient_evidence",
          "no_invoice": "not_applicable", "unknown_code": "requires_review", "duplicate": "requires_review"}


def _amt(cents):
    return f"{abs(cents):09d} {'C' if cents < 0 else 'D'}"


def _invoice(po, n, rng, currency="USD", bad_trailer=False, code=None):
    lines = [rng.randint(20_000, 120_000), rng.randint(1_000, 20_000)]  # linehaul, fuel (cents)
    if rng.random() < 0.5:
        lines.append(-rng.randint(500, 5_000))                           # accessorial credit
    codes = ["LHL", "FSC", "ACC"][:len(lines)]
    if code:
        codes[-1] = code
    net = sum(lines)
    text = [f"HDR KFL-INV-{n:05d}  {po}    {currency} 20261017"]
    text += [f"LIN {i + 1:03d} {c} {_amt(v)}  charge" for i, (c, v) in enumerate(zip(codes, lines))]
    text.append(f"TRL {len(lines) + (1 if bad_trailer else 0):03d} {_amt(net)}")
    return net, text


def build(n, seed=7):
    """-> (dataset, truth). truth[po] = {"status": ..., "value_cents": proposed value or None}."""
    rng, records, evidence, truth = random.Random(seed), [], [], {}
    for i in range(n):
        po, cls = f"PO-{100000 + i}", CLASSES[i % len(CLASSES)]
        net, lines = _invoice(po, i, rng, currency="CAD" if cls == "cad" else "USD",
                              bad_trailer=cls == "bad_trailer", code="DTY" if cls == "unknown_code" else None)
        accrued = net if cls != "wrong" else net + rng.choice([-1, 1]) * rng.randint(1, 40_000)  # within max_abs_change
        records.append({"id": po, "kind": "freight_po",
                        "data": {"label": f"lane {i % 17}", "currency": "USD", "freight_accrued": accrued / 100}})
        if cls != "no_invoice":
            evidence.append({"record_id": po, "source": "carrier_export", "trusted": True, "data": {"lines": lines}})
        if cls == "duplicate":
            evidence.append({"record_id": po, "source": "carrier_export", "trusted": True, "data": {"lines": lines}})
        truth[po] = {"status": EXPECT[cls], "value_cents": net if cls == "wrong" else None}
    rng.shuffle(evidence)  # evidence order is not record order (as in a real export)
    return {"name": f"synthetic freight n={n}", "description": "SYNTHETIC: generated by experiments/perf/gen.py",
            "records": records, "evidence": evidence, "policy": POLICY}, truth


if __name__ == "__main__":
    json.dump(build(int(sys.argv[1]))[0], sys.stdout)
